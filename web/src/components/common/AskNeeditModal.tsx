import React, { useState, useRef, useEffect } from 'react';
import {
  Sparkles,
  X,
  Send,
  AlertTriangle,
  Bot,
  User,
  RefreshCw,
  HelpCircle,
  ChevronDown,
  ChevronUp,
  Square,
} from 'lucide-react';
import {
  streamCampusAiMessage,
  resetActiveChatSession,
  getFirebaseAiStatus,
  CampusChatMessage,
} from '../../services/firebase';

interface AskNeeditModalProps {
  isOpen: boolean;
  onClose: () => void;
  onNavigate?: (path: string) => void;
}

interface DisplayMessage {
  id: string;
  role: 'user' | 'model';
  text: string;
  timestamp: Date;
  isError?: boolean;
  isStreaming?: boolean;
}

export const AskNeeditModal: React.FC<AskNeeditModalProps> = ({
  isOpen,
  onClose,
  onNavigate,
}) => {
  const [query, setQuery] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const [messages, setMessages] = useState<DisplayMessage[]>([]);
  const [showSuggestions, setShowSuggestions] = useState(true);
  const messagesEndRef = useRef<HTMLDivElement>(null);
  const abortControllerRef = useRef<AbortController | null>(null);
  const isSendingRef = useRef(false);

  const aiStatus = getFirebaseAiStatus();

  // Optional suggested prompt starters
  const suggestedPrompts = [
    'Where can I buy graph paper?',
    'Explain how NEEDIT works',
    'What can you help me with?',
    'What food is allowed on campus?',
  ];

  const scrollToBottom = () => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  };

  useEffect(() => {
    if (messages.length > 0) {
      scrollToBottom();
    }
  }, [messages, isLoading]);

  // Clean cancellation if modal is closed
  const handleClose = () => {
    if (abortControllerRef.current) {
      abortControllerRef.current.abort();
      abortControllerRef.current = null;
    }
    setIsLoading(false);
    isSendingRef.current = false;
    onClose();
  };

  /**
   * Execute sending a message with explicit baseMessages array.
   * Guarantees that:
   * 1. Only completed (user, model) pairs from previous turns are passed to Gemini.
   * 2. Failed or incomplete user messages are never sent as trailing history items.
   * 3. Multiple clicks or race conditions are locked via isSendingRef.
   */
  const executeSendMessage = async (
    textToSend: string,
    baseMessages: DisplayMessage[]
  ) => {
    const trimmed = textToSend.trim();
    if (!trimmed || isSendingRef.current) return;

    isSendingRef.current = true;
    setIsLoading(true);

    // Cancel any pending request before starting a new one
    if (abortControllerRef.current) {
      abortControllerRef.current.abort();
      abortControllerRef.current = null;
    }
    const controller = new AbortController();
    abortControllerRef.current = controller;

    const userMsg: DisplayMessage = {
      id: `user-${Date.now()}`,
      role: 'user',
      text: trimmed,
      timestamp: new Date(),
    };

    const assistantMsgId = `model-${Date.now()}`;
    const initialAssistantMsg: DisplayMessage = {
      id: assistantMsgId,
      role: 'model',
      text: '',
      timestamp: new Date(),
      isStreaming: true,
    };

    setShowSuggestions(false);
    setMessages([...baseMessages, userMsg, initialAssistantMsg]);
    setQuery('');

    // Extract valid history from baseMessages
    // Only completed, non-error pairs of user and model messages are used
    const historyPayload: CampusChatMessage[] = [];
    let pendingUserText: string | null = null;

    for (const msg of baseMessages) {
      if (msg.isError) {
        pendingUserText = null;
        continue;
      }
      if (msg.role === 'user') {
        pendingUserText = msg.text.trim() || null;
      } else if (msg.role === 'model') {
        if (pendingUserText && msg.text.trim() && !msg.isStreaming) {
          historyPayload.push({ role: 'user', text: pendingUserText });
          historyPayload.push({ role: 'model', text: msg.text.trim() });
          pendingUserText = null;
        }
      }
    }

    try {
      // Stream tokens progressively as they are generated by Gemini
      await streamCampusAiMessage(historyPayload, trimmed, {
        signal: controller.signal,
        onChunk: (chunkText) => {
          setMessages((prev) =>
            prev.map((msg) =>
              msg.id === assistantMsgId
                ? { ...msg, text: msg.text + chunkText }
                : msg
            )
          );
        },
      });

      // Finalize assistant message
      setMessages((prev) =>
        prev.map((msg) =>
          msg.id === assistantMsgId ? { ...msg, isStreaming: false } : msg
        )
      );
    } catch (err: any) {
      if (controller.signal.aborted || err?.name === 'AbortError') {
        // Clean cancellation: preserve partial text if received, or remove empty placeholder & orphan user message
        setMessages((prev) => {
          const assistantMsg = prev.find((m) => m.id === assistantMsgId);
          const hasAssistantText = (assistantMsg?.text || '').trim().length > 0;
          if (!hasAssistantText) {
            // Remove both the empty assistant placeholder AND the user message that had no response
            return prev.filter((m) => m.id !== assistantMsgId && m.id !== userMsg.id);
          }
          // If partial text was received, keep it with isStreaming: false
          return prev.map((msg) =>
            msg.id === assistantMsgId ? { ...msg, isStreaming: false } : msg
          );
        });
        return;
      }

      console.error('[Ask NEEDIT] Error from Gemini API:', err);
      setMessages((prev) =>
        prev.map((msg) =>
          msg.id === assistantMsgId
            ? {
                ...msg,
                text: err?.message || 'Failed to communicate with Firebase AI Logic.',
                isError: true,
                isStreaming: false,
              }
            : msg
        )
      );
    } finally {
      setIsLoading(false);
      isSendingRef.current = false;
      abortControllerRef.current = null;
    }
  };

  const handleSendMessage = (textToSend: string) => {
    executeSendMessage(textToSend, messages);
  };

  const handleStop = () => {
    if (abortControllerRef.current) {
      abortControllerRef.current.abort();
      abortControllerRef.current = null;
    }
    setIsLoading(false);
    isSendingRef.current = false;
  };

  const handleResetConversation = () => {
    if (abortControllerRef.current) {
      abortControllerRef.current.abort();
      abortControllerRef.current = null;
    }
    resetActiveChatSession();
    setMessages([]);
    setShowSuggestions(true);
    setIsLoading(false);
    isSendingRef.current = false;
  };

  /**
   * Safely retries the last failed message without duplicating it in history.
   * Strips the error card and the failed user message before re-executing.
   */
  const handleRetryLast = () => {
    if (isLoading || isSendingRef.current) return;

    const lastUserMsg = [...messages].reverse().find((m) => m.role === 'user');
    if (!lastUserMsg) return;

    // Remove the failed model error message and the failed user message
    const cleanedBase = messages.filter(
      (m) => !m.isError && m.id !== lastUserMsg.id
    );

    executeSendMessage(lastUserMsg.text, cleanedBase);
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-[500] flex justify-end">
      {/* Scrim backdrop */}
      <div
        className="fixed inset-0 bg-neutral-ink/40 backdrop-blur-sm modal-backdrop-anim"
        onClick={handleClose}
      />

      {/* Sheet / Drawer panel */}
      <div className="relative w-full max-w-lg bg-white dark:bg-neutral-dark-card h-full shadow-e3 flex flex-col z-10 overflow-hidden border-l border-neutral-border dark:border-neutral-dark-border sheet-slide-right">
        {/* Header */}
        <div className="p-4 sm:p-5 border-b border-neutral-border dark:border-neutral-dark-border flex items-center justify-between bg-neutral-surface-alt/60 dark:bg-slate-900/50">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-full bg-brand-indigo text-white flex items-center justify-center shadow-sm">
              <Sparkles className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-heading font-bold text-neutral-ink dark:text-neutral-dark-text text-base">
                Ask NEEDIT
              </h3>
              <p className="text-xs text-neutral-secondary dark:text-neutral-dark-secondary">
                Campus Assistant
              </p>
            </div>
          </div>

          <div className="flex items-center gap-1.5">
            {messages.length > 0 && (
              <button
                onClick={handleResetConversation}
                className="w-8 h-8 rounded-full flex items-center justify-center text-neutral-secondary hover:text-neutral-ink hover:bg-neutral-border/60 transition-colors"
                title="Reset conversation"
              >
                <RefreshCw className="w-4 h-4" />
              </button>
            )}
            <button
              onClick={handleClose}
              className="w-9 h-9 rounded-full flex items-center justify-center text-neutral-secondary hover:text-neutral-ink hover:bg-neutral-border/60 transition-colors"
              aria-label="Close Ask NEEDIT"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Unconfigured Alert Banner (if Firebase credentials are missing) */}
        {!aiStatus.isConfigured && (
          <div className="px-4 py-2.5 bg-amber-50 dark:bg-amber-950/40 border-b border-amber-200 dark:border-amber-800 text-xs text-amber-900 dark:text-amber-200 flex items-start gap-2">
            <AlertTriangle className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
            <div className="flex-1">
              <span className="font-semibold block">Firebase AI Logic setup required</span>
              <span className="text-[11px] text-amber-700 dark:text-amber-300">
                To enable live Gemini streaming, add your credentials to <code className="bg-amber-100 dark:bg-amber-900/60 px-1 py-0.5 rounded font-mono">web/.env</code>.
              </span>
            </div>
          </div>
        )}

        {/* Content body: Focused Multi-turn Chat */}
        <div className="flex-1 overflow-y-auto p-4 sm:p-5 space-y-4">
          {/* Welcome chat bubble */}
          <div className="flex items-start gap-3">
            <div className="w-8 h-8 rounded-full bg-brand-indigo/10 text-brand-indigo flex items-center justify-center shrink-0 mt-1">
              <Bot className="w-4 h-4" />
            </div>
            <div className="bg-brand-indigo-light dark:bg-brand-indigo/15 rounded-2xl rounded-tl-sm p-4 text-xs sm:text-sm text-neutral-ink dark:text-neutral-dark-text max-w-[90%] border border-brand-indigo/10 shadow-sm leading-relaxed">
              <p className="font-semibold mb-1">Welcome to Ask NEEDIT!</p>
              <p className="text-neutral-secondary dark:text-neutral-dark-secondary">
                I am your SASTRA campus assistant. You can ask me how NeedIt peer delivery works, where official pickup spots are located, or campus logistics questions.
              </p>
            </div>
          </div>

          {/* Dynamic Conversation Messages */}
          {messages.map((m) => {
            const isUser = m.role === 'user';
            const isErr = m.isError;

            // Prevent ghost empty assistant bubbles from rendering
            if (!isUser && !m.text.trim() && !m.isStreaming && !isErr) {
              return null;
            }

            if (isErr) {
              return (
                <div key={m.id} className="flex items-start gap-2.5 justify-start">
                  <div className="w-7 h-7 rounded-full bg-rose-600 text-white flex items-center justify-center shrink-0 mt-1">
                    <AlertTriangle className="w-3.5 h-3.5" />
                  </div>
                  <div className="rounded-2xl p-4 text-xs sm:text-sm max-w-[88%] bg-rose-50 dark:bg-rose-950/40 border border-rose-200 dark:border-rose-800 text-rose-900 dark:text-rose-200 shadow-sm space-y-2">
                    <div className="font-semibold flex items-center gap-1.5">
                      <span>Unable to get response from Gemini</span>
                    </div>
                    <p className="text-xs text-rose-700 dark:text-rose-300 leading-relaxed font-mono">
                      {m.text}
                    </p>
                    <div className="pt-1">
                      <button
                        type="button"
                        onClick={handleRetryLast}
                        disabled={isLoading}
                        className="px-3 py-1 text-xs font-semibold rounded bg-rose-600 text-white hover:bg-rose-700 transition-colors inline-flex items-center gap-1 disabled:opacity-50"
                      >
                        <RefreshCw className="w-3 h-3" /> Retry Question
                      </button>
                    </div>
                  </div>
                </div>
              );
            }

            return (
              <div
                key={m.id}
                className={`flex items-start gap-2.5 ${isUser ? 'justify-end' : 'justify-start'}`}
              >
                {!isUser && (
                  <div className="w-7 h-7 rounded-full bg-brand-indigo text-white flex items-center justify-center shrink-0 mt-1">
                    <Sparkles className="w-3.5 h-3.5" />
                  </div>
                )}
                <div
                  className={`rounded-2xl p-3.5 text-xs sm:text-sm max-w-[85%] leading-relaxed ${
                    isUser
                      ? 'bg-brand-indigo text-white rounded-tr-sm shadow-sm'
                      : 'bg-white dark:bg-slate-800 text-neutral-ink dark:text-neutral-dark-text rounded-tl-sm border border-neutral-border dark:border-neutral-dark-border shadow-e1'
                  }`}
                >
                  {/* Streaming state rendering */}
                  {!isUser && m.isStreaming && !m.text ? (
                    <div className="flex items-center gap-1.5 py-0.5 text-xs text-neutral-secondary">
                      <span className="w-1.5 h-1.5 rounded-full bg-brand-indigo animate-bounce [animation-delay:-0.3s]" />
                      <span className="w-1.5 h-1.5 rounded-full bg-brand-indigo animate-bounce [animation-delay:-0.15s]" />
                      <span className="w-1.5 h-1.5 rounded-full bg-brand-indigo animate-bounce" />
                      <span className="text-xs ml-1 font-medium">Thinking...</span>
                    </div>
                  ) : (
                    <div className="whitespace-pre-line">
                      {m.text}
                      {m.isStreaming && (
                        <span className="inline-block w-1.5 h-3.5 bg-brand-indigo ml-0.5 animate-pulse align-middle" />
                      )}
                    </div>
                  )}

                  <span
                    className={`block text-[10px] mt-1.5 ${
                      isUser ? 'text-indigo-200 text-right' : 'text-neutral-placeholder text-left'
                    }`}
                  >
                    {m.timestamp.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                  </span>
                </div>
                {isUser && (
                  <div className="w-7 h-7 rounded-full bg-slate-200 dark:bg-slate-700 text-slate-700 dark:text-slate-200 flex items-center justify-center shrink-0 mt-1">
                    <User className="w-3.5 h-3.5" />
                  </div>
                )}
              </div>
            );
          })}

          <div ref={messagesEndRef} />

          {/* Suggested Questions Section */}
          <div className="pt-2">
            <div className="flex items-center justify-between mb-2">
              <span className="text-[11px] font-semibold text-neutral-secondary dark:text-neutral-dark-secondary uppercase tracking-wider flex items-center gap-1">
                <HelpCircle className="w-3.5 h-3.5" /> Suggested Questions
              </span>
              {messages.length > 0 && (
                <button
                  type="button"
                  onClick={() => setShowSuggestions(!showSuggestions)}
                  className="text-xs text-neutral-secondary hover:text-brand-indigo flex items-center gap-0.5"
                >
                  <span>{showSuggestions ? 'Hide' : 'Show'}</span>
                  {showSuggestions ? <ChevronUp className="w-3 h-3" /> : <ChevronDown className="w-3 h-3" />}
                </button>
              )}
            </div>

            {showSuggestions && (
              <div className="flex flex-wrap gap-1.5">
                {suggestedPrompts.map((prompt, idx) => (
                  <button
                    key={idx}
                    type="button"
                    onClick={() => handleSendMessage(prompt)}
                    disabled={isLoading}
                    className="text-xs px-3 py-1.5 rounded-full border text-left transition-colors bg-neutral-surface-alt/80 dark:bg-slate-800 text-neutral-body dark:text-neutral-dark-text border-neutral-border dark:border-neutral-dark-border hover:border-brand-indigo hover:text-brand-indigo disabled:opacity-50"
                  >
                    {prompt}
                  </button>
                ))}
              </div>
            )}
          </div>
        </div>

        {/* Input Footer with Progressive Stream Control */}
        <div className="p-4 border-t border-neutral-border dark:border-neutral-dark-border bg-white dark:bg-neutral-dark-card">
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendMessage(query);
            }}
            className="flex items-center gap-2"
          >
            <div className="relative flex-1">
              <input
                type="text"
                value={query}
                onChange={(e) => setQuery(e.target.value)}
                placeholder={isLoading ? 'Generating response...' : 'Ask any question about campus or NeedIt...'}
                disabled={isLoading}
                aria-label="Ask any question about campus or NeedIt"
                className="w-full h-11 px-3.5 rounded-input bg-neutral-surface-alt dark:bg-slate-800 border border-neutral-border dark:border-slate-700 text-sm text-neutral-ink dark:text-neutral-dark-text focus:outline-none focus:ring-2 focus:ring-brand-indigo disabled:opacity-60"
              />
            </div>

            {isLoading ? (
              <button
                type="button"
                onClick={handleStop}
                className="h-11 px-4 rounded-btn bg-neutral-border text-neutral-ink dark:bg-slate-700 dark:text-neutral-dark-text hover:bg-neutral-border/80 text-xs font-semibold transition-colors flex items-center gap-1.5 shrink-0"
                title="Stop generating"
              >
                <Square className="w-3.5 h-3.5 fill-current" />
                <span>Stop</span>
              </button>
            ) : (
              <button
                type="submit"
                disabled={!query.trim() || isLoading}
                className="h-11 px-4 rounded-btn bg-brand-indigo text-white text-sm font-medium hover:bg-brand-indigo-dark transition-colors shrink-0 disabled:opacity-50 disabled:cursor-not-allowed flex items-center gap-1.5"
              >
                <span>Ask</span>
                <Send className="w-3.5 h-3.5" />
              </button>
            )}
          </form>
        </div>
      </div>
    </div>
  );
};
